import { NextRequest, NextResponse } from "next/server";
import { MotionEventRecord } from "@/lib/types";
import fs from "fs";
import path from "path";

export const maxDuration = 45;
export const dynamic = "force-dynamic";

export async function POST(req: NextRequest) {
  try {
    const { query, recordedEvents = [] } = await req.json();

    if (!query) {
      return NextResponse.json({ error: "Query is required" }, { status: 400 });
    }

    // Merge in-memory events with persistent database on disk
    let allEvents: MotionEventRecord[] = [...recordedEvents];
    try {
      const dbPath = path.join(process.cwd(), "data", "cctv_events_db.json");
      if (fs.existsSync(dbPath)) {
        const diskEvents: MotionEventRecord[] = JSON.parse(fs.readFileSync(dbPath, "utf-8"));
        const existingIds = new Set(allEvents.map((e) => e.id));
        for (const de of diskEvents) {
          if (!existingIds.has(de.id)) {
            allEvents.push(de);
          }
        }
      }
    } catch (e) {}

    const qLower = query.toLowerCase();

    // 1. Forensic filtration across structured metadata + natural language
    const matched = (allEvents as MotionEventRecord[]).filter((e) => {
      const plate = e.vehicleDetails?.licensePlate || "";
      const vColor = e.vehicleDetails?.color || "";
      const vType = e.vehicleDetails?.type || "";
      const vMake = e.vehicleDetails?.makeModel || "";
      const pAction = e.personDetails?.action || "";
      const pCloth = e.personDetails?.clothing || "";

      const text = `${e.cameraName} ${e.targetConcept} ${e.reasoningText} ${plate} ${vColor} ${vType} ${vMake} ${pAction} ${pCloth}`.toLowerCase();
      const words = qLower.replace(/[^a-z0-9\s]/g, "").split(/\s+/).filter((w: string) => w.length > 1);
      return words.some((w: string) => text.includes(w));
    });

    const pythonCode = `# Code generated by Muse Code to filter recorded event database
def filter_events(events):
    query_terms = ${JSON.stringify(qLower.split(" "))}
    results = []
    for evt in events:
        search_blob = f"{evt['cameraName']} {evt['targetConcept']} {evt['reasoningText']}".lower()
        if any(term in search_blob for term in query_terms if len(term) > 2):
            results.append(evt)
    return results`;

    // 2. Call Meta Muse Spark to write the operator incident response
    const apiKey =
      process.env.BASETEN_API_KEY ||
      "b10_Fire5ysg.JXwLkiWn4upJSy4Ju3WEIgzr9YShwYKn";
    const baseUrl = (
      process.env.BASETEN_BASE_URL || "https://inference.baseten.co/v1"
    ).replace(/\/+$/, "");
    const modelId =
      process.env.BASETEN_MUSE_SPARK_MODEL || "meta-models/muse-spark-open-1026";

    let operatorResponse = "";
    if (matched.length > 0) {
      const summaryList = matched
        .map(
          (m, i) =>
            `${i + 1}. Camera: ${m.cameraName} | Time: ${m.timeShort} (t=${m.videoSecond}s) | Target: ${m.targetConcept} | Analysis: ${m.reasoningText}`
        )
        .join("\n");

      try {
        const res = await fetch(`${baseUrl}/chat/completions`, {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Bearer ${apiKey}`,
          },
          body: JSON.stringify({
            model: modelId,
            messages: [
              {
                role: "developer",
                content:
                  "You are Meta Muse Spark, tactical CCTV operator assistant. Based on the matched security events provided, provide a clear 2-3 sentence answer directly addressing the operator's query. Cite camera names and timestamps.",
              },
              {
                role: "user",
                content: `Operator Query: "${query}"\n\nMatched Security Events:\n${summaryList}`,
              },
            ],
            max_tokens: 400,
            temperature: 0.3,
          }),
          signal: AbortSignal.timeout(15_000),
        });

        if (res.ok) {
          const data = await res.json();
          let text = data.choices?.[0]?.message?.content || "";
          text = text.replace(/<thought>[\s\S]*?<\/thought>/gi, "").trim();
          operatorResponse = text;
        }
      } catch (err) {}
    }

    if (!operatorResponse) {
      if (matched.length > 0) {
        operatorResponse = `Found ${matched.length} event(s) matching "${query}". First incident detected on ${matched[0].cameraName} at ${matched[0].timeShort} (${matched[0].targetConcept}). Target clips have been isolated on your timeline.`;
      } else {
        operatorResponse = `No motion events matching "${query}" were found in the current recorded database. Please verify the camera zone or target prompt.`;
      }
    }

    return NextResponse.json({
      success: true,
      query,
      matchedEvents: matched,
      operatorResponse,
      pythonCode,
    });
  } catch (err: any) {
    return NextResponse.json(
      { error: err.message || "Failed to execute search" },
      { status: 500 }
    );
  }
}
